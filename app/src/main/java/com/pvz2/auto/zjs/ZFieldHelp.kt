    /** 动作类型的说明；查不到返回 null（列表里就不显示问号）。 */
    fun ofAction(label: String): String? = actions[label]

    /** 前缀（`位置.` / `起点.` / `终点.` / `cond.` / `$prefix.` …）都去掉再查。 */
    fun of(field: String?): String? {
        if (field.isNullOrBlank()) return null
        var k = field.replace("\$prefix.", "").replace("\${p}", "")
        for (p in listOf("位置.", "起点.", "终点.", "cond.", "条件.")) {
            if (k.startsWith(p)) k = k.removePrefix(p)
        }
        // aiImage1/2/3 → 共用一条说明
        if (k.startsWith("aiImage")) k = "aiImage1"
        // 候选字段带下标（cand.0.cond / cand.1.color…）→ 去掉下标查通用说明
        if (Regex("^cand\\.[0-9]+\\.").containsMatchIn(k)) {
            k = "cand." + k.substringAfterLast('.')
        }
        return map[k]
    }

    /** 测试用：所有键。 */
    fun keys(): Set<String> = map.keys
